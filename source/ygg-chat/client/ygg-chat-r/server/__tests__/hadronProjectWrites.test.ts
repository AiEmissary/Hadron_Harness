it('requires a fresh recovery observation and confirmed stop, without retrying an uncertain edit',()=>{
 const lease=approved(),rename=fs.renameSync.bind(fs)
 const fault=vi.spyOn(fs,'renameSync').mockImplementation((from,to)=>{rename(from,to);throw Error('Lost acknowledgement')})
 expect(()=>store.apply(lease,'owner','op',signal())).toThrow('Lost acknowledgement');fault.mockRestore()
 const plan=store.recoveryPlan('owner',lease.id)
 expect(plan).toMatchObject({reconcilable:true,files:[{state:'uncertain',observed:'matches-replacement'}]})
 expect(()=>store.reconcileAfterStop(lease,'owner',plan.inspectionHash,()=>{throw Error('Worker remains active')})).toThrow('Worker remains active')
 expect(()=>store.reconcileAfterStop(lease,'owner','stale',()=>{})).toThrow('observations changed')
 const result=store.reconcileAfterStop(lease,'owner',plan.inspectionHash,()=>{})
 expect(result.filesChanged).toBe(false);store.assertRecoveryClosed(lease,'owner')
 expect(fs.readFileSync(path.join(project,'example.txt'),'utf8')).toBe('replacement')
 expect(()=>store.apply(lease,'owner','op',signal())).toThrow('capability')
 expect(db.prepare('SELECT decision FROM hadron_project_recoveries').get().decision).toBe('keep_observed_files')
})
