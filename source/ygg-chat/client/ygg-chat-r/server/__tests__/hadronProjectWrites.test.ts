 const lease=approved(),prepare=db.prepare.bind(db)
 vi.spyOn(db,'prepare').mockImplementation((sql:unknown)=>{
   if(String(sql).includes("SET state='applied'")||String(sql).includes('SET state=? WHERE id=?'))throw Error('Receipt storage failed')
   return prepare(sql)
 })
 expect(()=>store.apply(lease,'owner','op',signal())).toThrow('Receipt storage failed')
 expect(fs.readFileSync(path.join(project,'example.txt'),'utf8')).toBe('replacement')
