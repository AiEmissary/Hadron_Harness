it('preserves the original rejected proposal and both reviews through one staged correction',()=>{
 const lease=draft(),first=store.snapshot(lease,'owner')
 store.recordReview(lease,'owner','b',first.snapshotHash,'changes_required','Use corrected content.')
 store.beginCorrection(lease,'owner')
 expect(store.snapshot(lease,'owner').batch).toBe(1)
 expect(store.snapshot(lease,'owner').files).toEqual([])
 store.propose(lease,'owner','corrected','example.txt',digest('original'),'corrected replacement')
 const corrected=store.snapshot(lease,'owner')
 expect(()=>store.recordReview(lease,'owner','b',first.snapshotHash,'approve','Old review')).toThrow('exact')
 store.recordReview(lease,'owner','b',corrected.snapshotHash,'approve','Corrected version is acceptable.')
 expect(()=>store.apply(lease,'owner','op',signal())).toThrow('superseded')
 store.apply(lease,'owner','corrected',signal())
 expect(fs.readFileSync(path.join(project,'example.txt'),'utf8')).toBe('corrected replacement')
 const history=store.inspect('owner',lease.id)
 expect(history.files).toMatchObject([{batch:0,state:'prepared'},{batch:1,state:'applied'}])
 expect(history.reviews.map((item:any)=>item.verdict)).toEqual(['changes_required','approve'])
})
